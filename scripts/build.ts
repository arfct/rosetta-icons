import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { Dataset } from '../src/types.ts';
import { compile, loadSource, packageVersion, ROOT, report } from './lib.ts';

const source = loadSource();
const { dataset, problems } = compile(source, packageVersion());
if (!report(problems)) process.exit(1);

mkdirSync(join(ROOT, 'dist'), { recursive: true });
writeFileSync(join(ROOT, 'dist/rosetta.json'), `${JSON.stringify(dataset, null, 1)}\n`);
writeFileSync(join(ROOT, 'dist/names.txt'), `${Object.keys(dataset.icons).join('\n')}\n`);
writeFileSync(join(ROOT, 'dist/llm.md'), llmGuide(dataset));
writeFileSync(join(ROOT, 'src/data.generated.ts'), generatedModule(dataset));

const count = Object.keys(dataset.icons).length;
console.log(
  `built ${count} icons, ${Object.keys(dataset.index).length} index keys → dist/rosetta.json, dist/llm.md, dist/names.txt, src/data.generated.ts`,
);

function generatedModule(data: Dataset): string {
  const names = Object.keys(data.icons)
    .map((n) => `  | '${n}'`)
    .join('\n');
  return [
    '// Generated by scripts/build.ts from data/ — do not edit.',
    "import type { Dataset } from './types.ts';",
    '',
    `export type IconName =\n${names};`,
    '',
    `export const dataset: Dataset = ${JSON.stringify(data)};`,
    '',
  ].join('\n');
}

/** A prompt-sized reference: the rules, then every canonical name grouped by category. */
function llmGuide(data: Dataset): string {
  const byCategory = new Map<string, string[]>();
  for (const icon of Object.values(data.icons)) {
    const list = byCategory.get(icon.category) ?? [];
    list.push(icon.name);
    byCategory.set(icon.category, list);
  }
  const libs = Object.values(data.libraries)
    .map((l) => `${l.name} (${l.naming}, e.g. \`${l.example}\`)`)
    .join(', ');
  const lines = [
    '# Rosetta icon names',
    '',
    `One name resolves to ${libs}.`,
    '',
    '## Rules',
    '',
    '- Names are lowercase kebab-case: subject first, then qualifier (`arrow-up`, `check-circle`, `user-plus`).',
    '- When unsure, use the Lucide name. Every mapped Lucide, Material, Heroicons and SF Symbols name is also accepted, in any casing or separator (`arrow_forward`, `square.and.arrow.up`, `ArrowRight`).',
    '- Append a style to ask for a filled glyph: `heart-fill` (or `heart.fill`, `heart-solid`). Libraries without fills fall back to the outline.',
    '- Reordered qualifiers resolve too (`circle-check` → `check-circle`), so pick the natural reading and move on.',
    '',
    `## Names (${Object.keys(data.icons).length})`,
    '',
  ];
  for (const [category, names] of [...byCategory.entries()].sort()) {
    lines.push(`**${category}**: ${names.join(', ')}`, '');
  }
  return `${lines.join('\n')}`;
}
